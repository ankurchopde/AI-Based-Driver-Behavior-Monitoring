% build_final_logic.m
mdl = 'driver_monitor_sim_mediapipe';

if bdIsLoaded(mdl), close_system(mdl, 0); end
load_system(mdl);

% 1. Add Detect Increase for Yawn Event
try add_block('simulink/Logic and Bit Operations/Detect Increase', [mdl, '/YAWN_EVENT']); catch, end
set_param([mdl, '/YAWN_EVENT'], 'Position', [750, 360, 780, 390]);
try add_line(mdl, 'YAWN_ACTIVE/1', 'YAWN_EVENT/1', 'autorouting', 'on'); catch, end

% Type convert YAWN_EVENT to Double for the MATLAB Function block
try add_block('simulink/Signal Attributes/Data Type Conversion', [mdl, '/YAWN_To_Double']); catch, end
set_param([mdl, '/YAWN_To_Double'], 'OutDataTypeStr', 'double', 'Position', [820, 360, 850, 390]);
try add_line(mdl, 'YAWN_EVENT/1', 'YAWN_To_Double/1', 'autorouting', 'on'); catch, end

% We already have BLINK_EVENT converted to double as 'To Double' (let's rename it to BLINK_To_Double)
try set_param([mdl, '/To Double'], 'Name', 'BLINK_To_Double'); catch, end

% 2. Add MATLAB Function Block for State Aggregator
% We will use a basic MATLAB Function block
try add_block('simulink/User-Defined Functions/MATLAB Function', [mdl, '/Drowsiness State Machine']); catch, end
set_param([mdl, '/Drowsiness State Machine'], 'Position', [950, 420, 1050, 500]);

% Configure the script for the MATLAB Function block
code = ['function [State, Alert] = evaluate_drowsiness(Face, MS_Duration, BlinkEvent, YawnEvent)\n' ...
    '    persistent blink_history yawn_history history_idx;\n' ...
    '    if isempty(blink_history)\n' ...
    '        blink_history = zeros(1200, 1);\n' ...
    '        yawn_history = zeros(1200, 1);\n' ...
    '        history_idx = 1;\n' ...
    '    end\n' ...
    '    \n' ...
    '    blink_history(history_idx) = BlinkEvent;\n' ...
    '    yawn_history(history_idx) = YawnEvent;\n' ...
    '    \n' ...
    '    history_idx = history_idx + 1;\n' ...
    '    if history_idx > 1200\n' ...
    '        history_idx = 1;\n' ...
    '    end\n' ...
    '    \n' ...
    '    blink_count = sum(blink_history);\n' ...
    '    yawn_count = sum(yawn_history);\n' ...
    '    \n' ...
    '    MS_THRESH = 2.0;\n' ...
    '    BLINK_THRESH = 15;\n' ...
    '    YAWN_THRESH = 3;\n' ...
    '    \n' ...
    '    if Face == 0\n' ...
    '        State = 3; %% NO_FACE\n' ...
    '        Alert = 0;\n' ...
    '    elseif MS_Duration >= MS_THRESH\n' ...
    '        State = 2; %% DROWSY\n' ...
    '        Alert = 1;\n' ...
    '    elseif yawn_count >= YAWN_THRESH || blink_count >= BLINK_THRESH\n' ...
    '        State = 1; %% WARNING\n' ...
    '        Alert = 0;\n' ...
    '    else\n' ...
    '        State = 0; %% NORMAL\n' ...
    '        Alert = 0;\n' ...
    '    end\n' ...
    'end\n'];

% Using the Stateflow API to inject code into the MATLAB Function block
sf = sfroot;
blk = sf.find('Path', [mdl, '/Drowsiness State Machine'], '-isa', 'Stateflow.EMChart');
blk.Script = sprintf(code);

% 3. Connect inputs to MATLAB Function block
% Inputs are: Face, MS_Duration, BlinkEvent, YawnEvent
try add_line(mdl, 'MediaPipe DEMUX/1', 'Drowsiness State Machine/1', 'autorouting', 'on'); catch, end
try add_line(mdl, 'MS_Mult/1', 'Drowsiness State Machine/2', 'autorouting', 'on'); catch, end
try add_line(mdl, 'BLINK_To_Double/1', 'Drowsiness State Machine/3', 'autorouting', 'on'); catch, end
try add_line(mdl, 'YAWN_To_Double/1', 'Drowsiness State Machine/4', 'autorouting', 'on'); catch, end

% 4. Add Output Scopes
try add_block('simulink/Sinks/Scope', [mdl, '/DROWSINESS_STATE Scope']); catch, end
set_param([mdl, '/DROWSINESS_STATE Scope'], 'Position', [1100, 410, 1130, 440]);
try add_line(mdl, 'Drowsiness State Machine/1', 'DROWSINESS_STATE Scope/1', 'autorouting', 'on'); catch, end

try add_block('simulink/Sinks/Scope', [mdl, '/DROWSINESS_ALERT Scope']); catch, end
set_param([mdl, '/DROWSINESS_ALERT Scope'], 'Position', [1100, 470, 1130, 500]);
try add_line(mdl, 'Drowsiness State Machine/2', 'DROWSINESS_ALERT Scope/1', 'autorouting', 'on'); catch, end

% Add Annotations for Documentation
ann = Simulink.Annotation([mdl, '/0=NORMAL, 1=WARNING, 2=DROWSY, 3=NO_FACE']);
ann.Position = [1050, 520];

ann2 = Simulink.Annotation([mdl, '/Live real-time timing must be verified during hardware testing.']);
ann2.Position = [1050, 550];

% 5. Verify Compilation
set_param(mdl, 'SimulationCommand', 'update');
disp('Model compiled successfully with FINAL Drowsiness Aggregator!');
save_system(mdl);
close_system(mdl);
